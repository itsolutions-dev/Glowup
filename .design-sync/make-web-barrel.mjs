// Regenerates .design-sync/web-barrel.mjs from packages/ui/src/index.ts.
// The barrel is the browser-facing public surface of @its/glowup-ui:
//   - navigator shells (DrawerNavigation / StackNavigation / CustomDrawerContent)
//     are dropped — they pull @react-navigation -> react-native-screens, whose
//     native specs don't bundle for the web;
//   - DateTimePicker is pinned to its .web implementation (esbuild has no
//     platform-extension resolution);
//   - SafeAreaProvider is re-exported so previews (and design-agent output)
//     can mount AppBar / SpeedDial, which read safe-area insets.
// Run from the repo root, then .ds-sync/prebuild-web-entry.mjs.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { transformSync } from "esbuild";

const OUT = ".design-sync/web-barrel.mjs";
const DROP = /Navigation\/(DrawerContent|DrawerNavigation|StackNavigation)/;
const HEADER =
  "// GENERATED by .design-sync/make-web-barrel.mjs — do not edit by hand.\n";
const EXTRA =
  "\n// --- web-only additions (see make-web-barrel.mjs) ---\n" +
  'export { SafeAreaProvider } from "react-native-safe-area-context";\n';

// Types do not exist at run time, so they have no place in a runtime barrel.
// The barrel re-exports them both as `export type { … }` blocks and as inline
// `type X` specifiers inside value exports; esbuild's TypeScript transform
// strips both (line-based stripping missed the inline form and the multi-line
// blocks). esbuild resolves through .design-sync/node_modules, like the forks.
const source = readFileSync("packages/ui/src/index.ts", "utf8")
  .split(/\r?\n/)
  .filter((l) => !DROP.test(l))
  .join("\n");
const lines = transformSync(source, { loader: "ts", format: "esm" }).code.split(
  "\n",
);
const body = lines
  .map((l) =>
    l.replace(
      '"./components/DateTimePicker"',
      '"./components/DateTimePicker.web"',
    ),
  )
  .map((l) => l.replace(/"\.\//g, '"../packages/ui/lib/module/'))
  .join("\n");

writeFileSync(OUT, HEADER + body + EXTRA);

// `node --check` parses without executing, so it neither resolves the deep
// imports into packages/ui/lib nor runs any module side effect. Guarding here
// is the difference between this failing and step 4 of the re-sync failing on
// a barrel nobody suspected.
try {
  execFileSync(process.execPath, ["--check", OUT], { stdio: "pipe" });
} catch (error) {
  console.error(`${OUT} was written but does not parse:\n`);
  console.error(error.stderr?.toString() || error.message);
  process.exit(1);
}

console.log("wrote " + OUT);
